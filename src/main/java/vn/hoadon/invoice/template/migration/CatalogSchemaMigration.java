package vn.hoadon.invoice.template.migration;

import com.fasterxml.jackson.databind.ObjectMapper;

import vn.hoadon.invoice.template.catalog.*;
import vn.hoadon.invoice.template.storage.DocumentStorage;

import java.sql.*;
import java.util.*;

public final class CatalogSchemaMigration {
    private CatalogSchemaMigration() {}

    public static void migrate(Connection c) throws Exception {
        boolean sqlServer = c.getMetaData().getDatabaseProductName().contains("SQL Server");
        String identity =
                sqlServer ? "BIGINT IDENTITY(1,1)" : "BIGINT GENERATED BY DEFAULT AS IDENTITY";
        for (String obsolete :
                List.of(
                        "invoice_template_field_usages",
                        "invoice_template_field_bindings",
                        "invoice_template_field_rules")) {
            if (table(c, obsolete)) {
                if (!rows(c, "SELECT id FROM " + obsolete).isEmpty())
                    throw new IllegalStateException(
                            "Bảng cấu hình chưa chuyển dữ liệu: " + obsolete);
                execute(c, "DROP TABLE " + obsolete);
            }
        }
        create(
                c,
                "invoice_template_field_groups",
                "id "
                        + identity
                        + " PRIMARY KEY,code VARCHAR(80) NOT NULL UNIQUE,label NVARCHAR(255) NOT"
                        + " NULL,sort_order INT NOT NULL,active BIT NOT NULL,lock_version BIGINT"
                        + " NOT NULL DEFAULT 0");
        create(
                c,
                "invoice_template_datasets",
                "id "
                        + identity
                        + " PRIMARY KEY,code VARCHAR(80) NOT NULL UNIQUE,label NVARCHAR(255) NOT"
                        + " NULL,parent_id BIGINT NULL,cardinality VARCHAR(8) NOT NULL,root_path"
                        + " NVARCHAR(700) NOT NULL,active BIT NOT NULL,lock_version BIGINT NOT NULL"
                        + " DEFAULT 0");
        create(
                c,
                "invoice_template_catalog_releases",
                "id "
                        + identity
                        + " PRIMARY KEY,code VARCHAR(64) NOT NULL UNIQUE,snapshot_json"
                        + " NVARCHAR(MAX) NOT NULL,content_hash VARCHAR(64) NOT NULL,published_by"
                        + " BIGINT NULL,published_at DATETIME2 NOT NULL");
        unique(c, "invoice_template_field_groups", "code", "UK_template_group_code");
        unique(c, "invoice_template_datasets", "code", "UK_template_dataset_code");
        unique(c, "invoice_template_catalog_releases", "code", "UK_template_catalog_code");
        if (!column(c, "invoice_template_fields", "xml_path")) return;
        var legacy = rows(c, "SELECT * FROM invoice_template_fields ORDER BY sort_order,id");
        for (String declaration :
                List.of(
                        "group_id BIGINT NULL",
                        "dataset_id BIGINT NULL",
                        "source_path NVARCHAR(700) NULL",
                        "value_type VARCHAR(16) NULL",
                        "max_length INT NULL",
                        "default_formatter VARCHAR(40) NULL",
                        "description NVARCHAR(2000) NULL")) {
            String name = declaration.substring(0, declaration.indexOf(' '));
            if (!column(c, "invoice_template_fields", name))
                execute(c, "ALTER TABLE invoice_template_fields ADD " + declaration);
        }
        Map<String, String> labels =
                Map.ofEntries(
                        Map.entry("common", "Thông tin chung"),
                        Map.entry("related", "Hóa đơn liên quan"),
                        Map.entry("seller", "Người bán"),
                        Map.entry("buyer", "Người mua"),
                        Map.entry("items", "Hàng hóa, dịch vụ"),
                        Map.entry("items.special", "Hàng hóa đặc thù"),
                        Map.entry("taxGroups", "Tổng hợp thuế"),
                        Map.entry("totals", "Tổng tiền"),
                        Map.entry("fees", "Phí"),
                        Map.entry("invoice", "Thông tin hóa đơn"));
        Map<String, Long> groups = new LinkedHashMap<>(), datasets = new LinkedHashMap<>();
        Map<String, String> roots = new LinkedHashMap<>();
        roots.put("document", "/HDon");
        datasets.put(
                "document",
                insert(
                        c,
                        "INSERT INTO"
                            + " invoice_template_datasets(code,label,parent_id,cardinality,root_path,active,lock_version)"
                            + " VALUES('document',?,NULL,'ONE','/HDon',1,0)",
                        "Thông tin hóa đơn"));
        for (var row : legacy) {
            String group = text(row, "group_code");
            if (!groups.containsKey(group))
                groups.put(
                        group,
                        insert(
                                c,
                                "INSERT INTO"
                                    + " invoice_template_field_groups(code,label,sort_order,active,lock_version)"
                                    + " VALUES(?,?,?,1,0)",
                                group,
                                labels.getOrDefault(group, group),
                                groups.size() * 10));
            if (flag(row, "repeated")) {
                String path = text(row, "xml_path");
                String root = path.substring(0, path.lastIndexOf('/'));
                roots.merge(
                        group,
                        root,
                        (a, b) -> {
                            while (!b.equals(a) && !b.startsWith(a + "/"))
                                a = a.substring(0, a.lastIndexOf('/'));
                            return a;
                        });
            }
        }
        for (String code :
                roots.keySet().stream()
                        .filter(k -> !k.equals("document"))
                        .sorted(Comparator.comparingInt(String::length))
                        .toList()) {
            String parent =
                    code.contains(".") ? code.substring(0, code.lastIndexOf('.')) : "document";
            if (!datasets.containsKey(parent))
                throw new IllegalStateException("Không tìm thấy danh sách cha: " + code);
            datasets.put(
                    code,
                    insert(
                            c,
                            "INSERT INTO"
                                + " invoice_template_datasets(code,label,parent_id,cardinality,root_path,active,lock_version)"
                                + " VALUES(?,?,?,'MANY',?,1,0)",
                            code,
                            labels.getOrDefault(code, code),
                            datasets.get(parent),
                            roots.get(code).substring(roots.get(parent).length() + 1)));
        }
        for (var row : legacy) {
            String dataset = flag(row, "repeated") ? text(row, "group_code") : "document",
                    path = text(row, "xml_path");
            String source = "INVOICE".equals(text(row, "binding_source")) ? "CONTEXT" : "XML";
            String selector =
                    source.equals("XML")
                            ? path.substring(roots.get(dataset).length() + 1)
                            : "invoice." + path.substring("invoices.".length());
            if (source.equals("CONTEXT") && !InvoiceExternalFieldRegistry.contextSupports(selector))
                throw new IllegalStateException("Nguồn hệ thống chưa được khai báo: " + path);
            String type = Objects.toString(row.get("source_type"), ""),
                    length = Objects.toString(row.get("source_length"), "");
            String valueType =
                    type.toLowerCase(Locale.ROOT).startsWith("ngày")
                            ? "DATE"
                            : length.matches("[0-9]+,[0-9]+") ? "DECIMAL" : "STRING";
            Integer maxLength = length.matches("[0-9]+") ? Integer.valueOf(length) : null;
            update(
                    c,
                    "UPDATE invoice_template_fields SET"
                        + " group_id=?,dataset_id=?,source_type=?,source_path=?,value_type=?,max_length=?,default_formatter='plainText',description=?"
                        + " WHERE id=?",
                    groups.get(text(row, "group_code")),
                    datasets.get(dataset),
                    source,
                    selector,
                    valueType,
                    maxLength,
                    type + "; " + Objects.toString(row.get("requirement_text"), ""),
                    number(row, "id"));
        }
        long presentationGroup =
                insert(
                        c,
                        "INSERT INTO"
                            + " invoice_template_field_groups(code,label,sort_order,active,lock_version)"
                            + " VALUES('presentation',?,10000,0,0)",
                        "Thông tin bản in");
        Map<String, String> presentation =
                Map.of(
                        "sourceStage",
                        "Giai đoạn dữ liệu",
                        "statusLabel",
                        "Trạng thái hóa đơn",
                        "lookupCode",
                        "Mã tra cứu (bản in)",
                        "authorityCode",
                        "Mã cơ quan thuế (bản in)",
                        "signatureSummary",
                        "Thông tin chữ ký",
                        "sampleMarker",
                        "Dấu mẫu minh họa");
        for (String key :
                List.of(
                        "sourceStage",
                        "statusLabel",
                        "lookupCode",
                        "authorityCode",
                        "signatureSummary",
                        "sampleMarker")) {
            insert(
                    c,
                    "INSERT INTO"
                        + " invoice_template_fields(catalog_version,field_key,label,xml_path,binding_source,group_code,repeated,required_display,active,sort_order,created_at,updated_at,lock_version,group_id,dataset_id,source_type,source_path,value_type,default_formatter)"
                        + " VALUES('migration',?,?,?,'INVOICE','presentation',0,0,0,10000,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,0,?,?,'CONTEXT',?,'STRING','plainText')",
                    "presentation." + key,
                    presentation.get(key),
                    "presentation." + key,
                    presentationGroup,
                    datasets.get("document"),
                    "document." + key);
        }
        Set<String> codes = new LinkedHashSet<>();
        legacy.forEach(row -> codes.add(text(row, "catalog_version")));
        for (String owner : List.of("invoice_template_drafts", "invoice_template_versions"))
            if (table(c, owner))
                rows(c, "SELECT DISTINCT field_catalog_version FROM " + owner)
                        .forEach(row -> codes.add(text(row, "field_catalog_version")));
        if (codes.isEmpty()) codes.add("invoice-xml-2.1.1/catalog-1");
        for (String code : codes) snapshot(c, code);
        if (sqlServer) {
            for (var row :
                    rows(
                            c,
                            "SELECT dc.name FROM sys.default_constraints dc JOIN sys.columns cl ON"
                                + " cl.object_id=dc.parent_object_id AND"
                                + " cl.column_id=dc.parent_column_id WHERE"
                                + " dc.parent_object_id=OBJECT_ID('invoice_template_fields') AND"
                                + " cl.name IN"
                                + " ('catalog_version','xml_path','binding_source','group_code','repeated','source_length','source_type','requirement_text','status','numeric_precision','numeric_scale')"))
                execute(
                        c,
                        "ALTER TABLE invoice_template_fields DROP CONSTRAINT ["
                                + text(row, "name").replace("]", "]]")
                                + "]");
            for (var row :
                    rows(
                            c,
                            "SELECT name,is_unique_constraint FROM sys.indexes WHERE"
                                + " object_id=OBJECT_ID('invoice_template_fields') AND name IN"
                                + " ('UK_invoice_template_fields_xml_path','IX_invoice_template_fields_list')"))
                execute(
                        c,
                        flag(row, "is_unique_constraint")
                                ? "ALTER TABLE invoice_template_fields DROP CONSTRAINT ["
                                        + text(row, "name")
                                        + "]"
                                : "DROP INDEX ["
                                        + text(row, "name")
                                        + "] ON invoice_template_fields");
        } else {
            execute(c, "DROP INDEX IF EXISTS UK_invoice_template_fields_xml_path");
            execute(c, "DROP INDEX IF EXISTS IX_invoice_template_fields_list");
        }
        for (String col :
                List.of(
                        "catalog_version",
                        "xml_path",
                        "binding_source",
                        "group_code",
                        "repeated",
                        "source_length",
                        "requirement_text",
                        "numeric_precision",
                        "numeric_scale",
                        "status"))
            if (column(c, "invoice_template_fields", col))
                execute(c, "ALTER TABLE invoice_template_fields DROP COLUMN " + col);
        for (String col :
                List.of(
                        "group_id",
                        "dataset_id",
                        "source_type",
                        "source_path",
                        "value_type",
                        "default_formatter"))
            execute(
                    c,
                    "ALTER TABLE invoice_template_fields ALTER COLUMN "
                            + col
                            + switch (col) {
                                case "source_type" -> " VARCHAR(20) NOT NULL";
                                case "source_path" -> " NVARCHAR(700) NOT NULL";
                                case "value_type" -> " VARCHAR(16) NOT NULL";
                                case "default_formatter" -> " VARCHAR(40) NOT NULL";
                                default -> " BIGINT NOT NULL";
                            });
        execute(
                c,
                "ALTER TABLE invoice_template_fields ADD CONSTRAINT FK_template_field_group FOREIGN"
                    + " KEY(group_id) REFERENCES invoice_template_field_groups(id)");
        execute(
                c,
                "ALTER TABLE invoice_template_fields ADD CONSTRAINT FK_template_field_dataset"
                    + " FOREIGN KEY(dataset_id) REFERENCES invoice_template_datasets(id)");
        execute(
                c,
                "ALTER TABLE invoice_template_datasets ADD CONSTRAINT FK_template_dataset_parent"
                    + " FOREIGN KEY(parent_id) REFERENCES invoice_template_datasets(id)");
        execute(
                c,
                "ALTER TABLE invoice_template_fields ADD CONSTRAINT CK_template_field_type"
                    + " CHECK(source_type IN ('XML','CONTEXT') AND value_type IN"
                    + " ('STRING','INTEGER','DECIMAL','DATE','BOOLEAN') AND (max_length IS NULL OR"
                    + " max_length>0))");
        execute(
                c,
                "CREATE INDEX IX_template_field_list ON"
                    + " invoice_template_fields(active,group_id,sort_order,id)");
        if (sqlServer) {
            for (String owner : List.of("drafts", "versions"))
                if (table(c, "invoice_template_" + owner))
                    execute(
                            c,
                            "ALTER TABLE invoice_template_"
                                    + owner
                                    + " ADD CONSTRAINT FK_template_"
                                    + owner
                                    + "_catalog FOREIGN KEY(field_catalog_version) REFERENCES"
                                    + " invoice_template_catalog_releases(code)");
            execute(
                    c,
                    "CREATE OR ALTER TRIGGER TR_invoice_template_catalog_immutable ON"
                        + " invoice_template_catalog_releases AFTER UPDATE,DELETE AS BEGIN SET"
                        + " NOCOUNT ON; IF EXISTS(SELECT 1 FROM deleted) THROW 51041, 'Published"
                        + " catalog is immutable.', 1; END");
        }
    }

    public static void snapshot(Connection c, String code) throws Exception {
        var groups =
                rows(c, "SELECT * FROM invoice_template_field_groups ORDER BY sort_order,id")
                        .stream()
                        .map(
                                r ->
                                        new InvoiceCatalogSnapshot.Group(
                                                number(r, "id"),
                                                text(r, "code"),
                                                text(r, "label"),
                                                integer(r, "sort_order"),
                                                flag(r, "active"),
                                                number(r, "lock_version")))
                        .toList();
        var ds = rows(c, "SELECT * FROM invoice_template_datasets ORDER BY id");
        Map<Long, String> datasetCodes = new HashMap<>(), groupCodes = new HashMap<>();
        ds.forEach(r -> datasetCodes.put(number(r, "id"), text(r, "code")));
        groups.forEach(g -> groupCodes.put(g.id(), g.code()));
        var datasets =
                ds.stream()
                        .map(
                                r ->
                                        new InvoiceCatalogSnapshot.Dataset(
                                                number(r, "id"),
                                                text(r, "code"),
                                                text(r, "label"),
                                                datasetCodes.get(number(r, "parent_id")),
                                                text(r, "cardinality"),
                                                text(r, "root_path"),
                                                flag(r, "active"),
                                                number(r, "lock_version")))
                        .toList();
        var fields =
                rows(c, "SELECT * FROM invoice_template_fields ORDER BY sort_order,id").stream()
                        .map(
                                r ->
                                        new InvoiceCatalogSnapshot.Field(
                                                number(r, "id"),
                                                text(r, "field_key"),
                                                text(r, "label"),
                                                groupCodes.get(number(r, "group_id")),
                                                datasetCodes.get(number(r, "dataset_id")),
                                                datasets.stream()
                                                        .anyMatch(
                                                                d ->
                                                                        d.id().equals(
                                                                                                number(
                                                                                                        r,
                                                                                                        "dataset_id"))
                                                                                && "MANY"
                                                                                        .equals(
                                                                                                d
                                                                                                        .cardinality())),
                                                text(r, "source_type"),
                                                text(r, "source_path"),
                                                text(r, "value_type"),
                                                integer(r, "max_length"),
                                                text(r, "default_formatter"),
                                                text(r, "description"),
                                                flag(r, "required_display"),
                                                flag(r, "active"),
                                                integer(r, "sort_order"),
                                                number(r, "lock_version")))
                        .toList();
        var snapshot = new InvoiceCatalogSnapshot(code, groups, datasets, fields);
        InvoiceCatalogValidator.validate(snapshot);
        String json = new ObjectMapper().writeValueAsString(snapshot);
        insert(
                c,
                "INSERT INTO"
                    + " invoice_template_catalog_releases(code,snapshot_json,content_hash,published_at)"
                    + " VALUES(?,?,?,CURRENT_TIMESTAMP)",
                code,
                json,
                DocumentStorage.sha256(json));
    }

    private static void unique(Connection c, String table, String column, String constraint)
            throws Exception {
        Map<String, Set<String>> indexes = new HashMap<>();
        boolean sqlServer = c.getMetaData().getDatabaseProductName().contains("SQL Server");
        try (var rs =
                c.getMetaData()
                        .getIndexInfo(
                                c.getCatalog(),
                                sqlServer ? "dbo" : "PUBLIC",
                                sqlServer ? table : table.toUpperCase(Locale.ROOT),
                                true,
                                false)) {
            while (rs.next()) {
                String name = rs.getString("INDEX_NAME"), col = rs.getString("COLUMN_NAME");
                if (name != null && col != null)
                    indexes.computeIfAbsent(name, k -> new HashSet<>())
                            .add(col.toLowerCase(Locale.ROOT));
            }
        }
        if (indexes.values().stream().noneMatch(cols -> cols.equals(Set.of(column))))
            execute(
                    c,
                    "ALTER TABLE "
                            + table
                            + " ADD CONSTRAINT "
                            + constraint
                            + " UNIQUE("
                            + column
                            + ")");
    }

    static boolean table(Connection c, String name) throws Exception {
        return !rows(
                        c,
                        "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE LOWER(TABLE_NAME)=?"
                            + " AND TABLE_TYPE='BASE TABLE'",
                        name)
                .isEmpty();
    }

    static boolean column(Connection c, String table, String col) throws Exception {
        return !rows(
                        c,
                        "SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE"
                            + " LOWER(TABLE_NAME)=? AND LOWER(COLUMN_NAME)=?",
                        table,
                        col)
                .isEmpty();
    }

    private static void create(Connection c, String table, String definition) throws Exception {
        if (!table(c, table)) execute(c, "CREATE TABLE " + table + "(" + definition + ")");
    }

    private static Long number(Map<String, Object> r, String key) {
        return r.get(key) == null ? null : ((Number) r.get(key)).longValue();
    }

    private static Integer integer(Map<String, Object> r, String key) {
        return r.get(key) == null ? null : ((Number) r.get(key)).intValue();
    }

    private static String text(Map<String, Object> r, String key) {
        return r.get(key) == null ? null : r.get(key).toString();
    }

    private static boolean flag(Map<String, Object> r, String key) {
        return Boolean.TRUE.equals(r.get(key))
                || (r.get(key) instanceof Number n && n.intValue() != 0);
    }

    static void execute(Connection c, String sql) throws Exception {
        try (var s = c.createStatement()) {
            s.execute(sql);
        }
    }

    static void update(Connection c, String sql, Object... args) throws Exception {
        try (var s = c.prepareStatement(sql)) {
            for (int i = 0; i < args.length; i++) s.setObject(i + 1, args[i]);
            s.executeUpdate();
        }
    }

    private static long insert(Connection c, String sql, Object... args) throws Exception {
        try (var s = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            for (int i = 0; i < args.length; i++) s.setObject(i + 1, args[i]);
            s.executeUpdate();
            try (var rs = s.getGeneratedKeys()) {
                if (!rs.next()) throw new IllegalStateException("Missing generated ID");
                return rs.getLong(1);
            }
        }
    }

    private static List<Map<String, Object>> rows(Connection c, String sql, Object... args)
            throws Exception {
        try (var s = c.prepareStatement(sql)) {
            for (int i = 0; i < args.length; i++) s.setObject(i + 1, args[i]);
            try (var rs = s.executeQuery()) {
                var meta = rs.getMetaData();
                List<Map<String, Object>> result = new ArrayList<>();
                while (rs.next()) {
                    Map<String, Object> row = new LinkedHashMap<>();
                    for (int i = 1; i <= meta.getColumnCount(); i++)
                        row.put(meta.getColumnLabel(i).toLowerCase(Locale.ROOT), rs.getObject(i));
                    result.add(row);
                }
                return result;
            }
        }
    }
}
